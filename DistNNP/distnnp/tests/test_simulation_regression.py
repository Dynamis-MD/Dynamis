@pytest.mark.parametrize("n_steps", [1, 5, 10, 15, 20])
def test_energy_matches_baseline(simulation_factory, n_steps, request):
    integrator_name = request.node.callspec.params.get("simulation_factory")
    
    # Skip langevin, it is tested seperately
    if integrator_name == "langevin":
        pytest.skip("langevin tested seperately")

    simulation = simulation_factory()
    device = simulation.state.pos.device

    fixture = torch.load(FIXTURES_DIR / f"lj_reference_{integrator_name}.pt", map_location=device)
    reference = fixture[n_steps]

    for _ in range(n_steps - 1):
        simulation.step()

    energy, _ = simulation.step()

    # Each rank holds a partial energy; sum across ranks to get the total system energy.
    dist.all_reduce(energy, op=dist.ReduceOp.SUM)

    if dist.get_rank() == 0:
        torch.testing.assert_close(reference["energy"], energy, atol=2e-5, rtol=1e-6)
        
# Langevin canonical-ensemble check. Compares the single-GPU reference
# (in the fixture) against a fresh multi-GPU run of the same system —
# same atoms, same params, only the Langevin noise seed differs.
#
# Per side: N_RUNS_TEST independent trajectories. Each trajectory's
# post-equilibration KE/PE values are time-averaged into a single scalar,
# so the KS test compares two arrays of N_RUNS_TEST scalars (not the raw
# per-step time series).
#
# Why long runs: tau = 1/gamma = ~1000 steps. N_EQUIL = 1*tau (compromise from
# 2*tau to halve runtime) lets the system mostly forget its initial state;
# the remaining 1.5*tau averages over roughly one decorrelation window.
#
# Why KS instead of Z/t: no normality assumption, catches mean OR variance
# shifts. Power floor at N=4 vs N=4: smallest achievable p is ~0.029, so
# alpha must stay above that.
N_RUNS_TEST = 4
N_STEPS = 2500
N_EQUIL = 1000
# Bonferroni for 2 scalar tests at 5% overall. (Cannot go below ~0.029 at N=4.)
# This is fairly arbitrary, maybe could be tuned.
ALPHA = 0.05 / 2


def _langevin_run_means(sim, n_steps, n_equil):
    """Time-average total KE and total PE over post-equilibration steps of
    one trajectory. Each call advances `sim` by `n_steps` total steps.
    Returns (ke_mean, pe_mean) on rank 0; (None, None) on other ranks.
    """
    ke_acc, pe_acc = [], []
    for step in range(1, n_steps + 1):
        energy, _ = sim.step()
        if step > n_equil:
            local = sim.state.local_state
            local_masses = TORCH_MASSES.to(local.atom_positions.device)[local.atom_types.reshape(-1)]
            local_ke = 0.5 * (local_masses.unsqueeze(1) * local.atom_velocities ** 2).sum()
            dist.all_reduce(local_ke, op=dist.ReduceOp.SUM)
            total_pe = energy.clone()
            dist.all_reduce(total_pe, op=dist.ReduceOp.SUM)
            if dist.get_rank() == 0:
                ke_acc.append(local_ke.item())
                pe_acc.append(total_pe.item())
    if dist.get_rank() != 0:
        return None, None
    return sum(ke_acc) / len(ke_acc), sum(pe_acc) / len(pe_acc)


def test_langevin_matches_baseline(simulation_factory, request):
    """Langevin is stochastic and chaotic, so we cannot compare microscopic
    per-atom values across single- and multi-GPU runs. Instead run a few
    long independent trajectories per side, time-average total KE and PE
    over the post-equilibration window of each, and compare the per-run
    distributions with a 2-sample Kolmogorov-Smirnov test. See the
    comments above for the rationale on N_STEPS / N_EQUIL / ALPHA.
    """

    integrator_name = request.node.callspec.params.get("simulation_factory")
    if integrator_name != "langevin":
        pytest.skip("langevin-only test")

    fixture = torch.load(FIXTURES_DIR / f"lj_reference_{integrator_name}.pt", map_location="cpu")
    ref_ke = fixture["ke_per_run"].to(torch.float64).numpy()
    ref_pe = fixture["pe_per_run"].to(torch.float64).numpy()

    test_ke, test_pe = [], []
    for run in range(N_RUNS_TEST):
        sim = simulation_factory()
        # Seed for reproducability
        torch.manual_seed(2000 + run)
        ke_mean, pe_mean = _langevin_run_means(sim, N_STEPS, N_EQUIL)
        if dist.get_rank() == 0:
            test_ke.append(ke_mean)
            test_pe.append(pe_mean)

    if dist.get_rank() != 0:
        return

    test_ke = np.asarray(test_ke, dtype=np.float64)
    test_pe = np.asarray(test_pe, dtype=np.float64)

    for name, ref, test in (("KE", ref_ke, test_ke), ("PE", ref_pe, test_pe)):
        stat, p = ks_2samp(ref, test)
        assert p > ALPHA, (
            f"langevin {name} distribution diverges from reference: "
            f"KS stat={stat:.4f}, p={p:.4f} <= alpha={ALPHA:.4f}"
        )
