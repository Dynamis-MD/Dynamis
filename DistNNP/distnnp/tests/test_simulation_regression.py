"""
test_simulation_regression.py — regression tests for the Simulation class.

Reference system: 32-atom LJ argon in a 10x10x10 box, fixed seed=100.
Reference outputs generated by distnnp/tests/fixtures/generate_reference.py
and stored in distnnp/tests/fixtures/lj_reference_rank{r}.pt.

Each .pt file contains:
    {
        1:  {"positions": Tensor(n_local, 3), "forces": Tensor(n_local, 3)},
        10: {"positions": Tensor(n_local, 3), "forces": Tensor(n_local, 3)},
    }

Run via:
    torchrun --nproc_per_node=2 -m pytest distnnp/tests/test_simulation_regression.py -v
"""

import torch
import pytest
from pathlib import Path
import torch.distributed as dist

FIXTURES_DIR = Path(__file__).parent / "fixtures"
ATOL = 1e-5


@pytest.mark.parametrize("n_steps", [1, 10])
def test_forces_match_baseline(simulation_factory, n_steps, request):
    rank = dist.get_rank()
    integrator_name = request.node.callspec.params.get("simulation_factory")

    fixture = torch.load(FIXTURES_DIR / f"lj_reference_{integrator_name}_rank{rank}.pt")
    reference = fixture[n_steps]

    simulation = simulation_factory()

    for _ in range(n_steps - 1):
        simulation.step()

    _, forces = simulation.step()

    torch.testing.assert_close(reference["forces"], forces, atol=1e-5, rtol=0)


@pytest.mark.parametrize("n_steps", [1, 10])
def test_positions_match_baseline(simulation_factory, n_steps, request):
    rank = dist.get_rank()
    integrator_name = request.node.callspec.params.get("simulation_factory")

    fixture = torch.load(FIXTURES_DIR / f"lj_reference_{integrator_name}_rank{rank}.pt")
    reference = fixture[n_steps]

    simulation = simulation_factory()

    for _ in range(n_steps):
        simulation.step()

    torch.testing.assert_close(reference["positions"], simulation.state.pos, atol=1e-5, rtol=0)
